// SAT ScoreBoost -- regenerates the Supabase question import SQL.
//
// Loads js/questions.js, js/questions/*.js and js/choice-explanations/*.js in
// index.html script order and
// writes:
//   supabase/import_questions.sql        -- the whole bank in one file (psql)
//   supabase/import/import_questions_NN.sql -- the same rows split into parts
//     small enough for the dashboard SQL Editor; run every part, in any order.
//
// Usage: node supabase/generate_import.js
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const PART_LIMIT_BYTES = 700 * 1024; // SQL Editor rejects queries around 1 MB
const COLUMNS = ["id", "module", "domain", "skill", "difficulty", "passage", "prompt", "choices", "answer", "explanation", "choice_explanations"];
const OPTIONAL = new Set(["passage", "choice_explanations"]);

function questionScripts() {
  const html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8");
  const srcs = [...html.matchAll(/<script src="(js\/(?:questions\.js|questions\/[^"]+\.js|choice-explanations\/[^"]+\.js))"/g)].map((m) => m[1]);
  if (!srcs.length || srcs[0] !== "js/questions.js") throw new Error("js/questions.js must load first in index.html");
  return srcs;
}

function loadQuestions() {
  // `const QUESTIONS` is script-scoped, so run every file in one script.
  const code = questionScripts().map((src) => fs.readFileSync(path.join(ROOT, src), "utf8")).join("\n;\n");
  const ctx = {};
  vm.runInNewContext(code + "\n;globalThis.__out = QUESTIONS; globalThis.__why = typeof CHOICE_EXPLANATIONS === 'undefined' ? {} : CHOICE_EXPLANATIONS;", ctx);
  return ctx.__out.map((q) => {
    const why = ctx.__why[q.id];
    return { ...q, choice_explanations: Array.isArray(why) && why.length === q.choices.length ? why : null };
  });
}

function quote(text) {
  const s = String(text);
  if (s.includes("$q$")) throw new Error("Text contains the $q$ quote delimiter: " + s.slice(0, 80));
  return "$q$" + s + "$q$";
}

function rowSql(q) {
  for (const col of COLUMNS) {
    if (!OPTIONAL.has(col) && (q[col] === undefined || q[col] === null)) throw new Error(`Question ${q.id} is missing ${col}`);
  }
  const values = [
    quote(q.id),
    quote(q.module),
    quote(q.domain),
    quote(q.skill),
    Number(q.difficulty),
    q.passage == null ? "null" : quote(q.passage),
    quote(q.prompt),
    quote(JSON.stringify(q.choices)) + "::jsonb",
    Number(q.answer),
    quote(q.explanation),
    q.choice_explanations == null ? "null" : quote(JSON.stringify(q.choice_explanations)) + "::jsonb",
  ];
  return "  (" + values.join(", ") + ")";
}

function statement(rows, note) {
  return [
    "-- SAT ScoreBoost -- bulk import of the practice question bank into public.questions",
    "-- Generated by supabase/generate_import.js -- do not hand-edit, regenerate instead.",
    "-- Run in the Supabase SQL editor AFTER schema.sql (requires write access, i.e. run as yourself in the dashboard).",
    note ? "-- " + note : null,
    "",
    "-- Allow difficulty 4 (Extra Hard); harmless to repeat in every part.",
    "alter table public.questions drop constraint if exists questions_difficulty_check;",
    "alter table public.questions add constraint questions_difficulty_check check (difficulty between 1 and 4);",
    "",
    "insert into public.questions",
    "  (" + COLUMNS.join(", ") + ")",
    "values",
    rows.join(",\n"),
    "on conflict (id) do update set",
    COLUMNS.slice(1).map((c) => `  ${c} = excluded.${c}`).join(",\n") + ";",
    "",
  ].filter((line) => line !== null).join("\n");
}

function main() {
  const questions = loadQuestions();
  const ids = new Set();
  for (const q of questions) {
    if (ids.has(q.id)) throw new Error("Duplicate question id: " + q.id);
    ids.add(q.id);
  }
  const rows = questions.map(rowSql);

  fs.writeFileSync(path.join(__dirname, "import_questions.sql"), statement(rows));

  const parts = [];
  let current = [];
  let size = 0;
  for (const row of rows) {
    const bytes = Buffer.byteLength(row, "utf8") + 2;
    if (current.length && size + bytes > PART_LIMIT_BYTES) {
      parts.push(current);
      current = [];
      size = 0;
    }
    current.push(row);
    size += bytes;
  }
  if (current.length) parts.push(current);

  const dir = path.join(__dirname, "import");
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir);
  parts.forEach((partRows, i) => {
    const name = `import_questions_${String(i + 1).padStart(2, "0")}.sql`;
    const note = `Part ${i + 1} of ${parts.length} (${partRows.length} questions). Run every part.`;
    fs.writeFileSync(path.join(dir, name), statement(partRows, note));
  });

  console.log(`${questions.length} questions -> import_questions.sql + ${parts.length} parts in supabase/import/`);
}

main();
